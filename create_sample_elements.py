"""
创建产品要素表示例数据
"""
import pandas as pd

# 创建示例数据
sample_data = {
    "产品名称": [
        "元康盛景28号",
        "元康稳盈1号",
        "元康增益3号",
        "惠民1次",
        "惠民2次",
        "惠民3次"
    ],
    "申赎渠道": [
        "直销+代销",
        "直销",
        "直销+银行",
        "银行",
        "银行+券商",
        "直销+银行"
    ],
    "申购到账时间(T+N)": [1, 1, 0, 0, 0, 0],
    "赎回到账时间(T+N)": [3, 3, 1, 1, 1, 1],
    "备注": [
        "FOF产品，投资于多个子基金",
        "稳健型产品，仅限直销",
        "高收益产品，支持银行渠道",
        "流动性好，银行主销",
        "短期产品，多渠道销售",
        "新发行产品"
    ]
}

# 创建DataFrame
df = pd.DataFrame(sample_data)

# 保存到Excel
df.to_excel("产品要素表.xlsx", index=False)

print("✅ 产品要素表示例数据已创建！")
print(f"\n包含 {len(df)} 个产品的要素信息")
print("\n字段说明：")
print("- 产品名称：产品的完整名称")
print("- 申赎渠道：产品申购赎回的渠道（如：直销、代销、银行、券商等）")
print("- 申购到账时间(T+N)：申购后资金确认到账所需工作日数")
print("- 赎回到账时间(T+N)：赎回后资金到账所需工作日数")
print("- 备注：其他说明事项")
print("\n文件已保存为：产品要素表.xlsx")
